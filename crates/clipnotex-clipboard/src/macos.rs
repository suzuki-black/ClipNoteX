// Source detection
// ---------------------------------------------------------------------------

/// Detect the app that wrote to the clipboard.
///
/// Priority (DESIGN §4.2):
///  1. `org.nspasteboard.source` — written by the source app itself.
///  2. `NSWorkspace.frontmostApplication`.
///
/// Called from the blocking read task; NSWorkspace queries are safe off-main.
fn detect_source_blocking(types: &[String]) -> SourceApp {
    detect_source().unwrap_or_else(|| detect_source_from_pasteboard_types(types))
}

/// Read `org.nspasteboard.source` if present.
fn detect_source_from_pasteboard_types(types: &[String]) -> SourceApp {
    if types.contains(&"org.nspasteboard.source".to_string()) {
        if let Some(src) = read_nspasteboard_source() {
            return src;
        }
    }
    detect_frontmost().unwrap_or_default()
}

fn read_nspasteboard_source() -> Option<SourceApp> {
    // SAFETY: pasteboard read, blocking thread.
    unsafe {
        let pb = NSPasteboard::generalPasteboard();
        let items = pb.pasteboardItems()?;
        let first = items.first()?;
        let key = NSString::from_str("org.nspasteboard.source");
        let data = first.dataForType(&key)?;
        // The source bundle identifier is stored as a UTF-8 string.
        let bundle_id = String::from_utf8(data.bytes().to_vec()).ok()?;
        Some(SourceApp {
            bundle_id: Some(bundle_id.clone()),
            display_name: bundle_id,
            ..Default::default()
        })
    }
}

fn detect_frontmost() -> Option<SourceApp> {
    // SAFETY: NSWorkspace.sharedWorkspace and frontmostApplication are safe.
    unsafe {
        let ws = NSWorkspace::sharedWorkspace();
        let app = ws.frontmostApplication()?;
        let bundle_id = app.bundleIdentifier().map(|s| s.to_string());
        let display_name = app
            .localizedName()
            .map(|s| s.to_string())
            .unwrap_or_default();
        Some(SourceApp {
            bundle_id,
            display_name,
            ..Default::default()
        })
    }
}

pub fn detect_source() -> Option<SourceApp> {
    detect_frontmost()
}

// ---------------------------------------------------------------------------
// Writer
// ---------------------------------------------------------------------------

pub struct MacWriter;

impl MacWriter {
    pub fn new() -> Result<Self> {
        Ok(Self)
    }
}

impl ClipboardWriter for MacWriter {
    fn write(&self, payloads: &[PayloadData]) -> Result<()> {
        // SAFETY: NSPasteboard writes should happen on the main thread or in a
        // context where NSApplication has been initialized. Tauri ensures this.
        unsafe {
            let pb = NSPasteboard::generalPasteboard();
            pb.clearContents();

            // Build one NSPasteboardItem containing all formats.
            let item = NSPasteboardItem::new();
            for p in payloads {
                if p.bytes.is_empty() {
                    continue;
                }
                let uti = NSString::from_str(&p.format_id);
                let data = NSData::with_bytes(&p.bytes);
                // setData:forType: returns YES on success; log failures.
                if !item.setData_forType(&data, &uti) {
                    tracing::warn!("NSPasteboardItem setData failed for UTI: {}", p.format_id);
                }
            }
            // writeObjects: takes NSArray<ProtocolObject<dyn NSPasteboardWriting>>.
            // NSPasteboardItem conforms to NSPasteboardWriting via ImplementedBy.
            let writing: Retained<ProtocolObject<dyn NSPasteboardWriting>> =
                ProtocolObject::from_retained(item);
            let items = NSArray::from_vec(vec![writing]);
            if !pb.writeObjects(&items) {
                return Err(CnxError::Clipboard(
                    "NSPasteboard.writeObjects returned NO".into(),
                ));
            }
        }
        Ok(())
    }

    fn snapshot_for_restore(&self) -> Result<Vec<PayloadData>> {
        // SAFETY: blocking read, same rules as read_snapshot.
        let payloads: Vec<PayloadData> = unsafe {
            let pb = NSPasteboard::generalPasteboard();
            let items = match pb.pasteboardItems() {
                Some(i) => i,
                None => return Ok(vec![]),
            };
            let first = match items.first() {
                Some(i) => i,
                None => return Ok(vec![]),
            };
            let type_arr = first.types();
            let types: Vec<String> = (0..type_arr.len())
                .filter_map(|i| type_arr.get(i).map(|s| s.to_string()))
                .collect();
            types
                .iter()
                .filter(|t| is_mac_safe(t))
                .map(|uti| {
                    let bytes = read_item_data(first, uti);
                    PayloadData {
                        format_id: uti.clone(),
                        bytes,
                    }
                })
                .collect()
        };
        Ok(payloads)
    }
}
